const LEAGUE_FILTER_KEY = "leagueFilterBySport";
let selected = new Set();
let sport = "football";

const root = document.getElementById("catalogRoot");
const sportSelect = document.getElementById("sportSelect");
const saveStatus = document.getElementById("saveStatus");

function initials(name) {
  return String(name || "?")
    .split(/\s+/)
    .slice(0, 2)
    .map((w) => w[0] || "")
    .join("")
    .toUpperCase();
}

async function loadTheme() {
  const { "ext-theme": theme } = await chrome.storage.local.get("ext-theme");
  document.body.classList.toggle("dark", theme === "dark");
}

async function loadSelection() {
  const res = await chrome.storage.local.get(LEAGUE_FILTER_KEY);
  const raw = res[LEAGUE_FILTER_KEY] || {};
  selected = new Set((raw[sport] || []).map(String));
}

function allSlugsForSport() {
  const groups = LEAGUE_CATALOG[sport] || [];
  const out = [];
  groups.forEach((g) => g.leagues.forEach((l) => out.push(l.slug)));
  return out;
}

function render() {
  root.innerHTML = "";
  const groups = LEAGUE_CATALOG[sport] || [];
  if (!groups.length) {
    root.innerHTML =
      '<p class="sub">No competitions defined for this sport yet. Add them to LEAGUE_CATALOG in settings.js.</p>';
    return;
  }

  groups.forEach((group) => {
    const section = document.createElement("section");
    section.className = "country";

    const h2 = document.createElement("h2");
    const title = document.createElement("span");
    // title.textContent = group.country;
    title.textContent = t(group.country);
    h2.appendChild(title);

    const rowBtns = document.createElement("span");
    const allBtn = document.createElement("button");
    allBtn.type = "button";
    allBtn.textContent = t('all');
    allBtn.addEventListener("click", () => {
      group.leagues.forEach((l) => selected.add(l.slug));
      render();
    });
    const noneBtn = document.createElement("button");
    noneBtn.type = "button";
    noneBtn.textContent = t('none');
    noneBtn.addEventListener("click", () => {
      group.leagues.forEach((l) => selected.delete(l.slug));
      render();
    });
    rowBtns.append(allBtn, noneBtn);
    h2.appendChild(rowBtns);
    section.appendChild(h2);

    const grid = document.createElement("div");
    grid.className = "grid";

    group.leagues.forEach((league) => {
      const chip = document.createElement("label");
      chip.className =
        "chip" + (selected.has(league.slug) ? " selected" : "");
      chip.title = league.name;

      const cb = document.createElement("input");
      cb.type = "checkbox";
      cb.checked = selected.has(league.slug);
      cb.addEventListener("change", () => {
        if (cb.checked) selected.add(league.slug);
        else selected.delete(league.slug);
        chip.classList.toggle("selected", cb.checked);
      });

      if (league.logo) {
        const img = document.createElement("img");
        img.src = league.logo;
        img.alt = league.name;
        img.addEventListener("error", () => {
          const fb = document.createElement("div");
          fb.className = "fallback";
          fb.textContent = initials(league.name);
          img.replaceWith(fb);
        });
        chip.append(cb, img);
      } else {
        const fb = document.createElement("div");
        fb.className = "fallback";
        fb.textContent = initials(league.name);
        chip.append(cb, fb);
      }

      const hint = document.createElement("span");
      hint.className = "hint";
      hint.textContent = league.name;
      chip.appendChild(hint);

      grid.appendChild(chip);
    });

    section.appendChild(grid);
    root.appendChild(section);
  });
}

async function save() {
  const res = await chrome.storage.local.get(LEAGUE_FILTER_KEY);
  const all = res[LEAGUE_FILTER_KEY] || {};
  const arr = Array.from(selected);
  if (arr.length) all[sport] = arr;
  else delete all[sport];
  await chrome.storage.local.set({ [LEAGUE_FILTER_KEY]: all });
  saveStatus.textContent = t('saved_auto_update');
  setTimeout(() => {
    saveStatus.textContent = "";
  }, 2500);
}


