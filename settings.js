// YouTube Tab Reuse Permission

const tabReuseToggle = document.getElementById("enableTabReuseToggle");
const tabReuseStatus = document.getElementById("tabReuseStatus");
const tabReuseNote = document.getElementById("tabReuseNote");

async function updateTabReuseSetting() {
  if (!tabReuseToggle) return;

  try {
    const granted = await chrome.permissions.contains({
      permissions: ["tabs"]
    });

    tabReuseToggle.checked = granted;
    tabReuseToggle.disabled = false;

    tabReuseStatus.textContent = granted ? t("enabled") : t("disabled");
    tabReuseStatus.classList.toggle("enabled", granted);

    tabReuseNote.textContent = granted
      ? t("reuse_youtube_tab_active")
      : t("reuse_youtube_tab_hint");

  } catch (error) {
    console.error("Failed to check tabs permission:", error);

    tabReuseToggle.disabled = true;
    tabReuseStatus.textContent = "Unavailable";
  }
}

function refreshTabReuseLabels() {
  if (!tabReuseToggle || !tabReuseStatus || !tabReuseNote) return;

  const enabled = tabReuseToggle.checked;

  tabReuseStatus.textContent = enabled
    ? t("enabled")
    : t("disabled");

  tabReuseStatus.classList.toggle("enabled", enabled);

  tabReuseNote.textContent = enabled
    ? t("reuse_youtube_tab_active")
    : t("reuse_youtube_tab_hint");
}

tabReuseToggle?.addEventListener("change", async () => {
  const enable = tabReuseToggle.checked;

  tabReuseToggle.disabled = true;

  try {
    if (enable) {
      const granted = await chrome.permissions.request({
        permissions: ["tabs"]
      });

      if (!granted) {
        tabReuseToggle.checked = false;
      }
    } else {
      await chrome.permissions.remove({
        permissions: ["tabs"]
      });
    }
  } catch (error) {
    console.error("Failed to update tabs permission:", error);
  }

  await updateTabReuseSetting();
});

